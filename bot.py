# =============================================================
#  Простой Telegram-бот на Python с библиотекой aiogram 3
# =============================================================
#
#  Что умеет бот:
#    /start — здоровается с пользователем по имени
#    /help  — показывает список команд
#    любой другой текст — бот повторяет его обратно ("эхо")
#
#  Строки, которые начинаются с символа #, — это комментарии.
#  Python их не выполняет, они нужны только людям для пояснений.
# =============================================================


# --- 1. Импорты -------------------------------------------------
# "import" подключает готовый код из других модулей (библиотек),
# чтобы не писать всё самим.

import asyncio   # встроенный модуль Python для асинхронной работы
                 # (бот может ждать сообщения от многих людей сразу)
import logging   # встроенный модуль для вывода служебных сообщений в консоль
import os        # встроенный модуль для работы с операционной системой
                 # (нам он нужен, чтобы читать переменные окружения)

from dotenv import load_dotenv               # читает файл .env
from aiogram import Bot, Dispatcher, F       # основные классы aiogram
from aiogram.filters import Command, CommandStart
from aiogram.types import Message            # "Message" — это одно сообщение в чате


# --- 2. Настройки -----------------------------------------------

# Загружаем переменные из файла .env (там лежит секретный токен бота).
load_dotenv()

# Достаём токен по имени BOT_TOKEN. Если его нет — получим None.
BOT_TOKEN = os.getenv("BOT_TOKEN")

# Dispatcher (диспетчер) — это "регистратор": он получает все входящие
# сообщения и решает, какая функция должна на них ответить.
dp = Dispatcher()


# --- 3. Обработчики (handlers) ----------------------------------
# Обработчик — это функция, которая отвечает на определённый вид сообщений.
# Строка с @ над функцией называется "декоратор". Здесь она говорит
# диспетчеру: "когда придёт такое-то сообщение, вызови эту функцию".
#
# "async def" — объявление асинхронной функции.
# "await" — "подожди, пока действие (например, отправка ответа) завершится".


@dp.message(CommandStart())  # срабатывает на команду /start
async def cmd_start(message: Message):
    # message.from_user.first_name — имя человека, который написал боту.
    name = message.from_user.first_name
    # f"..." — f-строка: значения в {фигурных скобках} подставляются в текст.
    await message.answer(
        f"Привет, {name}! 👋\n"
        "Я учебный бот. Напиши мне что-нибудь, и я повторю.\n"
        "Список команд: /help"
    )


@dp.message(Command("help"))  # срабатывает на команду /help
async def cmd_help(message: Message):
    await message.answer(
        "Что я умею:\n"
        "/start — поздороваться\n"
        "/help — показать эту справку\n"
        "Любой другой текст я просто повторю."
    )


@dp.message(F.text)  # срабатывает на любое текстовое сообщение
async def echo(message: Message):
    # Этот обработчик стоит последним: диспетчер проверяет обработчики
    # сверху вниз, поэтому /start и /help сюда не попадут.
    await message.answer(message.text)


@dp.message()  # всё остальное: фото, стикеры, голосовые и т.д.
async def other(message: Message):
    await message.answer("Пока я понимаю только текст 🙂")


# --- 4. Запуск бота ---------------------------------------------

async def main():
    # Проверяем, что токен задан, иначе объясняем, что делать.
    if not BOT_TOKEN:
        raise SystemExit(
            "Не найден BOT_TOKEN. Создайте файл .env по образцу .env.example "
            "и вставьте туда токен от @BotFather."
        )

    # Bot — объект, через который мы общаемся с серверами Telegram.
    bot = Bot(token=BOT_TOKEN)

    print("Бот запущен. Нажмите Ctrl+C, чтобы остановить.")
    # start_polling — бот постоянно спрашивает Telegram: "есть новые сообщения?"
    # и передаёт их диспетчеру. Работает, пока мы не остановим программу.
    await dp.start_polling(bot)


# Эта проверка значит: "выполнить код ниже, только если файл запущен
# напрямую (python bot.py), а не подключён из другого файла".
if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)  # показывать служебные сообщения
    asyncio.run(main())                      # запускаем асинхронную функцию main
